##### Import #####
# Import that can't be in the try
from sys import exit, stderr

# Import that can be checked
try:
    from dataclasses import dataclass # Used for the constant classes
    from pathlib import Path # Used for the paths of the repository
    from os import environ # Used for the XDG directories
except ImportError as e:
    stderr.write(f"Import Error ({__file__}): {e}\n")
    exit(255)

# Check if the module is imported and not executed
if __name__ == "__main__":
    stderr.write(f"The {__file__} can only be imported and not executed!\n")
    exit(255)

##### Const #####
@dataclass(frozen=True)
class Return():
    """
        Return values
    """
    OK: int = 0 # Return value upon success
    KO: int = 1 # Return value upon fail

@dataclass(frozen=True)
class Error():
    """
        Error values
    """
    FATAL: int  = 0b1000    # Global error, the whole execution stops                  (100% execution stop)
    LOCAL: int  = 0b100     # Local error, the local execution probably can't go on   (some chance of execution stop)
    ACTION: int = 0b10      # Same~~ as Return.KO, an action of the program fails      (low chance of execution stop)

@dataclass(frozen=True)
class Files():
    """
        Paths of the repository and of the local data
    """
    ROOT: Path          = Path(__file__).resolve().parent.parent                   # Root of the repository
    SOURCES: Path       = ROOT / "sources.toml"                                    # Public sources
    PRIVATE: Path       = ROOT / "private.toml"                                    # Private sources (git ignored)
    PACKAGES: Path      = ROOT / "packages.json"                                   # Catalog generated by update.py
    README: Path        = ROOT / "README.md"                                       # README with the generated catalog
    SITE: Path          = ROOT / "site"                                            # Sources of the gh-pages site
    VENDOR: Path        = SITE / "vendor"                                          # html-style / better-html-style templates
    KEY: Path           = SITE / "RPM-GPG-KEY-tsukini"                             # Signing key of every package repository
    MIRROR: Path        = Path(environ.get("XDG_DATA_HOME", Path.home() / ".local/share")) / "universe"  # Local mirror

@dataclass(frozen=True)
class Values():
    """
        Fixed values of the catalog
    """
    CATEGORIES: tuple[str, ...]     = ("hand-made", "ai-made")     # Categories, in their display order
    FORMATS: tuple[str, ...]        = ("rpm", "deb", "arch")       # Package formats, in their display order
    PRE_SUFFIX: str                 = "-pre"                       # Suffix of the pre-release packages
    REPO_PREFIX: str                = "universe-"                  # Prefix of the dnf repository ids
    DEB_SUITE: str                  = "stable"                     # Suite of the debian repositories
    USER_AGENT: str                 = "my-universe-catalog"        # User agent of the http requests
    TIMEOUT: int                    = 30                           # Timeout of an http request (seconds)

@dataclass(frozen=True)
class Markers():
    """
        Markers of the generated parts of the README
    """
    BADGES_START: str   = "<!-- universe:badges:start -->"
    BADGES_END: str     = "<!-- universe:badges:end -->"
    CATALOG_START: str  = "<!-- universe:catalog:start -->"
    CATALOG_END: str    = "<!-- universe:catalog:end -->"

##### Declaration #####
RETURN  = Return()
ERROR   = Error()
FILES   = Files()
VALUES  = Values()
MARKERS = Markers()
